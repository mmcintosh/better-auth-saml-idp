if "<!-- roadmap:start" in readme:
    readme = re.sub(r"<!-- roadmap:start.*?<!-- roadmap:end -->", lambda m: block, readme, flags=re.S)
else:
    readme = re.sub(r"## Roadmap\n.*?(?=\n## Security)", lambda m: block + "\n", readme, flags=re.S)

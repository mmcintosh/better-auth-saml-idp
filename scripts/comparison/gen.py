md.append("\n## Sources\n")
for k, n, g, v, src in PRODUCTS:
    md.append(f"- **{n}** ({v}): " + ", ".join(f"[{t}]({u})" for t, u in src))
md.append(f"\nResearch method: three parallel reviews of vendor documentation (and source code where the docs were silent), {CHECKED}. Corrections welcome as issues or pull requests.\n")
open(os.path.join(ROOT, "docs/comparison.md"), "w").write("\n".join(md) + "\n")

